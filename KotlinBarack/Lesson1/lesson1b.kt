fun main(){
    // Datatypes:
        // 1.Numbers(Without Decimals):
            // a). Byte--> 0-127.(8 bits)
            // b). Short--> 127-32767.(16 bits)
            // c). Integer--> Known as "Int".(32 bits)
            // D). Long-->Longest/Biggest.(64 bits)
        val byteNumber : Byte = 127
        println(byteNumber)
        var shortNumber : Short = 32767
        println(shortNumber)
        var intNumber : Int = 32767
        println(intNumber)

        // 2. Decimals:
            // a). Float
            // b). Double
        val floatNumber : Float = 1.34F
        println(floatNumber)
        var doubleNumber : Double = 1.345
        println(doubleNumber)

        // 3. Text:
            // a). String: Ensure Double Quotes.
            // b). Character:Ensure single quotes and only takes letters.(Char)
        val textString : String = "Data Science"
        println(textString)
        var letterChar : Char = 'V'
        println(letterChar)

    //    End Main
}